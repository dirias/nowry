import React, { useRef, useEffect, useState } from 'react'
import { useTranslation } from 'react-i18next'
import { Box, Typography, useColorScheme } from '@mui/joy'
import WarningAmberRoundedIcon from '@mui/icons-material/WarningAmberRounded'
import mermaid from 'mermaid'
import DOMPurify from 'dompurify'
import { diagramThemeVariables } from '@nowry/core/tokens/diagramTheme'
import { useThemePreferences } from '../../theme/DynamicThemeProvider'

export default function MermaidRenderer({ code }) {
  const { t } = useTranslation()
  const { mode } = useColorScheme()
  const { themeColor } = useThemePreferences()
  const ref = useRef(null)
  const [svg, setSvg] = useState('')
  const [error, setError] = useState(null)

  useEffect(() => {
    if (code && ref.current) {
      // Re-initialize with correct theme before each render so light/dark
      // mode changes are reflected in the SVG output.
      //
      // Root cause of invisible text: Mermaid embeds a <style> block in the SVG
      // that defines node label colors. DOMPurify (v3) strips <style> blocks from
      // SVG by default (XSS vector). Without that <style>, text fill falls back to
      // the browser default and becomes invisible against the panel background.
      //
      // Fix: pass explicit themeVariables so Mermaid bakes color values into
      // inline SVG attributes (fill=, stroke=) rather than relying on a <style>
      // block. We also allow the Mermaid <style> through DOMPurify below since
      // it is generated by Mermaid, not from user input.
      const isDark = mode === 'dark'
      mermaid.initialize({
        startOnLoad: false,
        theme: 'base',
        // The page's own colours (ADR-074): grounds and text of the mode, the
        // learner's accent for a node. Values, because Mermaid cannot read a variable.
        themeVariables: { ...diagramThemeVariables(isDark ? 'dark' : 'light', themeColor), fontFamily: 'Inter, sans-serif' },
        securityLevel: 'loose',
        fontFamily: 'Inter, sans-serif',
        // Mermaid v10+ defaults to htmlLabels:true for flowchart/mindmap/ER,
        // rendering node text as <foreignObject> HTML. DOMPurify strips
        // <foreignObject> (XSS vector), leaving boxes with no visible text.
        // Force SVG-native <text> elements so all diagram types render correctly.
        htmlLabels: false
      })
      setSvg('')
      setError(null)
      const id = `mermaid-${Date.now()}`
      mermaid
        .render(id, code)
        .then((result) => {
          // Allow Mermaid's own <style> block through DOMPurify — it is
          // generated internally (not from user input) and contains the color
          // rules for node labels. Without it, SVG text nodes lose their fill.
          const clean = DOMPurify.sanitize(result.svg, {
            ADD_TAGS: ['style'],
            FORCE_BODY: false,
            USE_PROFILES: { svg: true, svgFilters: true }
          })
          setSvg(clean)
          setError(null)
        })
        .catch(() => {
          setError(t('aiMagic.diagram.renderError'))
        })
    }
  }, [code, mode, themeColor, t])

  if (error) {
    return (
      <Box
        sx={{
          p: 4,
          textAlign: 'center',
          color: 'danger.plainColor',
          bgcolor: 'danger.softBg',
          borderRadius: 'md'
        }}
      >
        <Typography level='title-md' sx={{ mb: 1 }} startDecorator={<WarningAmberRoundedIcon />}>
          {t('aiMagic.diagram.renderError')}
        </Typography>
      </Box>
    )
  }

  return (
    <div
      ref={ref}
      className='mermaid-diagram-host'
      dangerouslySetInnerHTML={{ __html: svg }}
      style={{ width: '100%', overflow: 'auto', textAlign: 'center' }}
    />
  )
}
